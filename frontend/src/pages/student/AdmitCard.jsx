import { useEffect, useState } from "react";
import { QRCodeSVG } from "qrcode.react";
import api, { errMsg, money } from "../../api.js";
import Logo from "../../components/Logo.jsx";

export default function AdmitCard() {
  const [c, setC] = useState(null);
  const [error, setError] = useState("");

  useEffect(() => {
    api.get("/student/admit-card").then((r) => setC(r.data)).catch((e) => setError(errMsg(e)));
  }, []);

  if (!c) return <p className="muted">{error || "Loading your admit card…"}</p>;

  const blocked = c.exams.filter((e) => !e.eligible);
  const verifyUrl = `${window.location.origin}/verify/admit?student=${encodeURIComponent(c.studentId)}&token=${encodeURIComponent(c.verifyToken)}`;

  return (
    <>
      <div className="no-print actions" style={{ marginBottom: "1rem" }}>
        <h1 className="page-title" style={{ margin: 0 }}>Exam admit card</h1>
        {c.exams.length > 0 && blocked.length < c.exams.length && (
          <button className="btn primary" onClick={() => window.print()}>Print / Save as PDF</button>
        )}
      </div>

      {blocked.length > 0 && (
        <div className="alert error no-print" role="alert">
          You cannot sit {blocked.length === c.exams.length ? "any exam" : "some exams"} yet:
          {c.feeCleared ? "" : ` your fees are not fully paid (${money(c.remainingBalance)} left).`}
          {" "}{blocked.some((e) => e.reasons.some((r) => r.startsWith("Attendance"))) ? `Attendance must be at least ${c.attendanceMinimum}%.` : ""}
        </div>
      )}

      {c.exams.length === 0 ? (
        <section className="panel"><p className="muted">No upcoming exams for your courses. Your card will appear here once exams are scheduled.</p></section>
      ) : (
        <section className="panel paper">
          <div className="paper-head">
            <Logo size={26} />
            <div className="right"><h1>Exam admit card</h1><span className="small muted">Issued {c.issuedOn}</span></div>
          </div>

          <div className="admit-top">
            <table className="kv">
              <tbody>
                <tr><th>Student</th><td>{c.studentName}</td></tr>
                <tr><th>Email</th><td>{c.email}</td></tr>
                <tr><th>Faculty / session</th><td>{c.faculty} · {c.session}</td></tr>
                <tr><th>Fees</th><td>{c.feeCleared ? "Cleared" : `${money(c.remainingBalance)} due`}</td></tr>
              </tbody>
            </table>
            <div className="admit-qr">
              <QRCodeSVG value={verifyUrl} size={110} />
              <span className="small muted">Scan to verify</span>
            </div>
          </div>

          <table>
            <thead><tr><th>Date</th><th>Time</th><th>Course</th><th>Room</th><th>Status</th></tr></thead>
            <tbody>
              {c.exams.map((e) => (
                <tr key={e.examId}>
                  <td>{e.date}</td>
                  <td>{e.startTime} – {e.endTime}</td>
                  <td><strong>{e.courseCode}</strong> {e.courseName}</td>
                  <td>{e.room}</td>
                  <td>
                    {e.eligible ? <span className="pill ok">Allowed</span> : (
                      <><span className="pill bad">Not allowed</span><div className="small">{e.reasons.join(". ")}</div></>
                    )}
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
          <p className="muted small">Bring this card and your ID to the exam hall. Computer-generated by TecSpace.</p>
        </section>
      )}
    </>
  );
}
