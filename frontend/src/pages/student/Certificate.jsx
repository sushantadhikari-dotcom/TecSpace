import { useEffect, useState } from "react";
import { Link, useParams } from "react-router-dom";
import api, { errMsg } from "../../api.js";
import Logo from "../../components/Logo.jsx";

export default function Certificate() {
  const { id } = useParams();
  const [c, setC] = useState(null);
  const [error, setError] = useState("");

  useEffect(() => {
    api.get(`/student/requests/${id}/certificate`).then((r) => setC(r.data)).catch((e) => setError(errMsg(e)));
  }, [id]);

  if (!c) return <p className="muted">{error || "Loading certificate…"}</p>;

  return (
    <>
      <div className="no-print actions" style={{ marginBottom: "1rem" }}>
        <Link to="/student/requests">Back to requests</Link>
        <button className="btn primary" onClick={() => window.print()}>Print / Save as PDF</button>
      </div>
      <section className="panel paper">
        <div className="paper-head">
          <Logo size={26} />
          <div className="right"><h1>{c.title}</h1><span className="mono">{c.referenceNo}</span></div>
        </div>
        <p style={{ fontSize: "1.1rem", lineHeight: 1.8, margin: "2rem 0" }}>{c.text}</p>
        <p className="muted">Issued on {c.issuedOn}</p>
        <p className="muted small">Computer-generated by TecSpace. The reference number can be used to verify this certificate.</p>
      </section>
    </>
  );
}
