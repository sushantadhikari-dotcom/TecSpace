import { useEffect, useState } from "react";
import api, { errMsg } from "../../api.js";
import Logo from "../../components/Logo.jsx";

export default function Transcript() {
  const [t, setT] = useState(null);
  const [error, setError] = useState("");

  useEffect(() => {
    api.get("/student/transcript").then((r) => setT(r.data)).catch((e) => setError(errMsg(e)));
  }, []);

  if (!t) return <p className="muted">{error || "Loading transcript…"}</p>;

  return (
    <>
      <div className="no-print actions" style={{ marginBottom: "1rem" }}>
        <h1 className="page-title" style={{ margin: 0 }}>Transcript</h1>
        {t.terms.length > 0 && <button className="btn primary" onClick={() => window.print()}>Print / Save as PDF</button>}
      </div>

      {t.terms.length === 0 ? (
        <section className="panel">
          <p className="muted">
            No report cards have been published yet. When the administration publishes a trimester's results,
            you will get a notification and it will appear here. Your live grades are always on the Grades page.
          </p>
        </section>
      ) : (
        <section className="panel paper">
          <div className="paper-head">
            <Logo size={26} />
            <div className="right">
              <h1>Academic transcript</h1>
              <span className="small muted">Issued {t.issuedOn}</span>
            </div>
          </div>

          <table className="kv">
            <tbody>
              <tr><th>Student</th><td>{t.studentName}</td></tr>
              <tr><th>Email</th><td>{t.email}</td></tr>
              <tr><th>Faculty / session</th><td>{t.faculty} · {t.session}</td></tr>
            </tbody>
          </table>

          {t.terms.map((term) => (
            <div key={term.name} className="term">
              <div className="panel-head">
                <h2>{term.name}</h2>
                <span className="pill">GPA {term.gpa.toFixed(2)} · {term.credits} credits</span>
              </div>
              <table>
                <thead><tr><th>Code</th><th>Course</th><th className="num">Credits</th><th className="num">Marks</th><th className="num">Grade</th></tr></thead>
                <tbody>
                  {term.courses.map((c) => (
                    <tr key={c.courseCode}>
                      <td className="mono">{c.courseCode}</td>
                      <td>{c.courseName}</td>
                      <td className="num">{c.creditHours}</td>
                      <td className="num">{c.percentage != null ? `${c.percentage}%` : "—"}</td>
                      <td className="num"><strong>{c.grade}</strong></td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          ))}

          <div className="paper-total">
            <span>Cumulative GPA · {t.totalCredits} credits</span>
            <strong>{t.cgpa.toFixed(2)}</strong>
          </div>
          <p className="muted small">This transcript lists published results only. Computer-generated by TecSpace.</p>
        </section>
      )}
    </>
  );
}
